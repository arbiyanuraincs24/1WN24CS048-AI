if __name__ == "__main__":
    # Initialize the world and the agent
    env = VacuumEnvironment()
    agent = ReflexVacuumAgent()

    print("🚀 Initializing Two-Location Vacuum Environment...")
    env.display_status()
    time.sleep(1)

    step = 1
    # Run the simulation until both rooms are clean
    while not env.is_all_clean() and step <= 5:
        print(f"\n⏱️ --- STEP {step} ---")

        # 1. Agent senses the environment (Percept)
        percept = env.get_percept()
        print(f"👀 Agent perceives: Location {percept[0]} is {percept[1]}")

        # 2. Agent chooses an action based on rules
        action = agent.program(percept)

        # 3. Environment reacts to the action
        env.execute_action(action)

        # 4. Show updated status
        env.display_status()

        step += 1
        time.sleep(1.5)

    if env.is_all_clean():
        print("\n✨ Success! All locations are perfectly clean. ✨")
    else:
        print("\n🛑 Simulation ended due to maximum steps reached.")