def check_win(board, player):
    """Returns True if the specified player has won the game."""
    win_conditions = [
        (0, 1, 2), (3, 4, 5), (6, 7, 8),  # Rows
        (0, 3, 6), (1, 4, 7), (2, 5, 8),  # Columns
        (0, 4, 8), (2, 4, 6)              # Diagonals
    ]
    return any(board[a] == board[b] == board[c] == player for a, b, c in win_conditions)

def check_tie(board):
    """Returns True if the board is completely full."""
    return " " not in board

def print_inline_boards(boards_list):
    """Prints a list of boards horizontally side-by-side with step markers."""
    for i in range(3):
        row_str = ""
        for step, board in enumerate(boards_list):
            idx = i * 3
            # Format one line of a 3x3 grid
            grid_line = f" {board[idx]} | {board[idx+1]} | {board[idx+2]} "

            # Add step text label on the middle row
            if i == 1:
                label = f"  (Step {step})  →  " if step < len(boards_list) - 1 else "  (Final)      "
            else:
                label = "               " if step < len(boards_list) - 1 else "               "

            row_str += grid_line + label
        print(row_str)
        if i < 2:
            divider_str = ""
            for step in range(len(boards_list)):
                divider_str += "---|---|---" + ("               " if step < len(boards_list) - 1 else "")
            print(divider_str)
    print("\n" + "="*80 + "\n")

def explore_tree(board, current_player, history=None):
    """Recursively traverses the tree and prints each path visually as it completes."""
    if history is None:
        # Start history with a copy of the root half-played board state
        history = [list(board)]

    last_player = "O" if current_player == "X" else "X"

    # Base Case 1: Last player won
    if check_win(board, last_player):
        global path_counter
        path_counter += 1
        print(f"PATH #{path_counter} | Outcome: {last_player} Wins | Path Cost: {len(history) - 1} moves")
        print_inline_boards(history)
        return

    # Base Case 2: Tie game
    if check_tie(board):
        path_counter += 1
        print(f"PATH #{path_counter} | Outcome: Tie Game | Path Cost: {len(history) - 1} moves")
        print_inline_boards(history)
        return

    # Find available spots
    empty_cells = [i for i, cell in enumerate(board) if cell == " "]

    # Branch out to all possible next turns
    for cell in empty_cells:
        next_board = list(board)
        next_board[cell] = current_player

        next_player = "O" if current_player == "X" else "X"
        explore_tree(next_board, next_player, history + [next_board])

