import random
import time

class VacuumEnvironment:
    def __init__(self):
        # Locations A and B can be either 'Clean' or 'Dirty'
        self.locations = {
            "A": random.choice(["Dirty"]),
            "B": random.choice(["Dirty"])
        }
        # Agent starts in a random location
        self.agent_location = random.choice(["A"])
        self.performance_score = 0

    def get_percept(self):
        """Returns the current location and its condition."""
        return self.agent_location, self.locations[self.agent_location]

    def execute_action(self, action):
        """Changes the environment state based on the agent's action."""
        print(f"🎬 Agent decides to: {action}")

        if action == "Suck":
            if self.locations[self.agent_location] == "Dirty":
                self.locations[self.agent_location] = "Clean"
                self.performance_score += 10  # Reward for cleaning
                print(f"🧹 Sucked dirt in Location {self.agent_location}.")
            else:
                self.performance_score -= 1   # Penalty for wasting energy
                print(f"⚠️ Tried to suck, but Location {self.agent_location} was already clean.")

        elif action == "Move_Right":
            if self.agent_location == "A":
                self.agent_location = "B"
                print("➡️ Moved from A to B.")
            self.performance_score -= 1       # Energy cost for movement

        elif action == "Move_Left":
            if self.agent_location == "B":
                self.agent_location = "A"
                print("⬅️ Moved from B to A.")
            self.performance_score -= 1       # Energy cost for movement

    def display_status(self):
        """Prints the current state of the environment."""
        print("\n" + "="*40)
        print(f"📍 Agent Location: {self.agent_location}")
        print(f"🏠 Status - Room A: {self.locations['A']} | Room B: {self.locations['B']}")


    def is_all_clean(self):
        """Checks if both locations are clean."""
        return self.locations["A"] == "Clean" and self.locations["B"] == "Clean"


class ReflexVacuumAgent:
    def __init__(self):
        pass

    def program(self, percept):
        """Reflex Agent rule logic: Condition -> Action"""
        location, status = percept

        if status == "Dirty":
            return "Suck"
        elif location == "A":
            return "Move_Right"
        elif location == "B":
            return "Move_Left"


